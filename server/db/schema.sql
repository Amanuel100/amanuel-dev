CREATE DATABASE IF NOT EXISTS amanuel_portfolio CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE amanuel_portfolio;
CREATE TABLE IF NOT EXISTS contacts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL, subject VARCHAR(150) NOT NULL,
  budget VARCHAR(30) NOT NULL, message TEXT NOT NULL,
  mail_status ENUM('pending','sending','sent') NOT NULL DEFAULT 'pending', mail_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_contacts_created (created_at), INDEX idx_contacts_mail (mail_status, mail_attempts, updated_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS projects (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(100) NOT NULL UNIQUE, title VARCHAR(150) NOT NULL, category VARCHAR(100) NOT NULL,
  year SMALLINT UNSIGNED NOT NULL, description TEXT NOT NULL, thumbnail VARCHAR(500) NOT NULL,
  accent_color CHAR(7) NOT NULL, live_url VARCHAR(500) NOT NULL DEFAULT '', repo_url VARCHAR(500) NOT NULL DEFAULT '', sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_projects_order (sort_order, id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS project_tech (
  project_id INT UNSIGNED NOT NULL, name VARCHAR(80) NOT NULL, sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (project_id, name), INDEX idx_tech_order (project_id, sort_order),
  CONSTRAINT fk_tech_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS testimonials (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  quote TEXT NOT NULL, name VARCHAR(100) NOT NULL, role VARCHAR(100) NOT NULL,
  company VARCHAR(150) NOT NULL, avatar VARCHAR(500) NOT NULL, published BOOLEAN NOT NULL DEFAULT TRUE, sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_testimonials_published (published, sort_order)
) ENGINE=InnoDB;
